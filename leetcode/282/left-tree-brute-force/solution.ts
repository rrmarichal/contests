import assert from "node:assert"

type Expression = {
  leftValue: number
  rightValue: number
  value: number
}

function _addOperators(
  num: string,
  low: number,
  high: number,
  T: Map<string, Expression>[][],
): Map<string, Expression> {
  if (T[low][high].size > 0) return T[low][high]

  if (num[low] != "0" || high == low) {
    T[low][high].set(num.substring(low, high + 1), {
      leftValue: parseInt(num.substring(low, high + 1)),
      rightValue: parseInt(num.substring(low, high + 1)),
      value: parseInt(num.substring(low, high + 1)),
    })
  }

  for (let i = low; i < high; i++) {
    if (num[i + 1] == "0" && i < high - 1) continue

    const left = _addOperators(num, low, i, T)
    const right = new Map<string, Expression>([
      [
        num.substring(i + 1, high + 1),
        {
          leftValue: parseInt(num.substring(i + 1, high + 1)),
          rightValue: parseInt(num.substring(i + 1, high + 1)),
          value: parseInt(num.substring(i + 1, high + 1)),
        },
      ],
    ])
    for (const l of left) {
      for (const r of right) {
        const lrem = l[1].value - l[1].rightValue
        const rrem = r[1].value - r[1].leftValue
        const value = l[1].rightValue * r[1].leftValue + lrem + rrem
        T[low][high].set(`${l[0]}*${r[0]}`, {
          leftValue: l[1].leftValue,
          rightValue: l[1].rightValue * r[1].value,
          value,
        })
        T[low][high].set(`${l[0]}+${r[0]}`, {
          leftValue: l[1].value,
          rightValue: r[1].value,
          value: l[1].value + r[1].value,
        })
        T[low][high].set(`${l[0]}-${r[0]}`, {
          leftValue: l[1].value,
          rightValue: -r[1].value,
          value: l[1].value - r[1].value,
        })
      }
    }
  }

  return T[low][high]
}

function addOperators(num: string, target: number): string[] {
  const T: Map<string, Expression>[][] = Array.from(
    { length: num.length },
    () =>
      Array.from({ length: num.length }, () => new Map<string, Expression>()),
  )
  _addOperators(num, 0, num.length - 1, T)
  return Array.from(T[0][num.length - 1])
    .filter((entry) => entry[1].value == target)
    .map((entry) => entry[0])
    .sort()
}

